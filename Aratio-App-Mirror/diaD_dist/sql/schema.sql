  `campana_id` int(11) NOT NULL,
  `nombres` varchar(100) NOT NULL,
  `apellidos` varchar(100) NOT NULL,
  `tipo_documento` enum('CC','TI','CE','PA','RC','NIT') DEFAULT 'CC',
  `documento` varchar(20) NOT NULL,
  `fecha_nacimiento` date NOT NULL,
  `genero` varchar(20) DEFAULT 'Otro',
  `perfil` varchar(100) DEFAULT 'Simpatizante',
  `nivel_liderazgo` int(11) DEFAULT 0,
  `nivel_participacion` enum('Simpatizante','Aportante','Activista de Opinion','Movilizador','Contradictor','Contratista') DEFAULT NULL,
  `areas_interes` longtext CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL CHECK (json_valid(`areas_interes`)),
  `dato_potencial` int(11) DEFAULT 0,
  `dato_historico` int(11) DEFAULT 0,
  `estado` varchar(20) DEFAULT 'Nuevo',
  `revision` datetime DEFAULT NULL,
  `departamento` varchar(100) NOT NULL,
  `municipio` varchar(100) NOT NULL,
  `tipo_territorio` varchar(50) DEFAULT NULL,
  `territorio` varchar(100) DEFAULT NULL,
  `barrio` varchar(100) DEFAULT NULL,
  `territorio_id` int(11) DEFAULT NULL,
  `direccion` varchar(255) DEFAULT NULL,
  `detalle_ubicacion` text DEFAULT NULL,
  `lider_directo` varchar(20) DEFAULT NULL COMMENT 'Documento del lider',
  `email` varchar(255) NOT NULL,
  `telefono` varchar(20) NOT NULL,
  `telefono_whatsapp` varchar(20) NOT NULL,
  `observaciones` text DEFAULT NULL,
  `usuario_registro_id` int(11) DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT current_timestamp(),
  `updated_at` timestamp NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  `puesto_votacion` varchar(255) DEFAULT NULL COMMENT 'Nombre del puesto de votacion',
  `mesa_votacion` varchar(10) DEFAULT NULL COMMENT 'Numero de mesa',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_doc_camp` (`documento`,`campana_id`),
  KEY `idx_campana` (`campana_id`),
  KEY `idx_perfil` (`perfil`),
  KEY `idx_lider` (`lider_directo`),
  KEY `idx_territorio` (`departamento`,`municipio`),
  KEY `idx_jerarquia` (`campana_id`,`lider_directo`,`documento`),
  KEY `idx_territorio_campana` (`campana_id`,`departamento`,`municipio`),
  KEY `idx_puesto_mesa` (`campana_id`,`puesto_votacion`,`mesa_votacion`)
) ENGINE=InnoDB AUTO_INCREMENT=1119 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

